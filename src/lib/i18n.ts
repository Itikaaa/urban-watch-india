let activeLocale: Locale = "en";

export function getLocale() {
  return activeLocale;
}

export function setActiveLocale(locale: Locale) {
  activeLocale = locale;
}

export function fill(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  let out = template;
  for (const [key, value] of Object.entries(vars)) {
    out = out.replaceAll(`{${key}}`, String(value));
  }
  return out;
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const table = locale === "hi" ? hi : en;
  return fill(table[key] ?? en[key], vars);
}

export function tKey(key: MessageKey, vars?: Record<string, string | number>) {
  return translate(activeLocale, key, vars);
}

export function hazardLabel(type: string, locale: Locale = activeLocale) {
  const key = HAZARD_KEYS[type];
  return key ? translate(locale, key) : type;
}

export function teamNameLabel(idOrName: string, locale: Locale = activeLocale) {
  const key = TEAM_NAME_KEYS[idOrName];
  return key ? translate(locale, key) : idOrName;
}

export function teamFocusLabel(teamId: string, locale: Locale = activeLocale) {
  const key = TEAM_FOCUS_KEYS[teamId];
  return key ? translate(locale, key) : teamId;
}

export function sightLabel(kind: string, fallback: string, locale: Locale = activeLocale) {
  const key = SIGHT_KEYS[kind];
  return key ? translate(locale, key) : fallback;
}

export function severityLabel(severity: string, locale: Locale = activeLocale) {
  if (severity === "critical") return translate(locale, "riskCritical");
  if (severity === "high") return translate(locale, "riskHigh");
  if (severity === "medium") return translate(locale, "riskMedium");
  return translate(locale, "riskLow");
}
